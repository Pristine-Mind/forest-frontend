/**
 * Convert Gregorian date to Nepali date
 * @param gregorianDate - JS Date object or ISO string
 * @returns Object with year, month, day in Nepali calendar (BS)
 */
export function gregorianToNepali(gregorianDate: Date | string) {
  const date = typeof gregorianDate === "string" ? new Date(gregorianDate) : gregorianDate;
  
  // Offset between Gregorian and Nepali calendars
  // 1945-01-01 AD = 2001-10-16 BS (approximately)
  const baseGregorian = new Date(1945, 0, 1); // Jan 1, 1945
  const baseNepali = { year: 2001, month: 10, day: 16 };

  const diffMs = date.getTime() - baseGregorian.getTime();
  const diffDays = Math.floor(diffMs / (1000 * 60 * 60 * 24));

  let nepaliYear = baseNepali.year;
  let nepaliMonth = baseNepali.month - 1;
  let nepaliDay = baseNepali.day + diffDays;

  // Adjust for Nepali calendar
  while (nepaliDay > 0) {
    const yearData = NEPALI_CALENDAR_DATA.find((data) => data[0] === nepaliYear);
    if (!yearData) break;

    const daysInMonth = yearData[nepaliMonth + 1];
    if (nepaliDay <= daysInMonth) break;

    nepaliDay -= daysInMonth;
    nepaliMonth++;

    if (nepaliMonth >= 12) {
      nepaliMonth = 0;
      nepaliYear++;
    }
  }

  return {
    year: nepaliYear,
    month: nepaliMonth + 1, // 1-based
    day: nepaliDay,
    monthName: NEPALI_MONTHS[nepaliMonth],
  };
}

/**
 * Convert Nepali date to Gregorian date
 * @param nepaliYear - Year in BS (e.g., 2081)
 * @param nepaliMonth - Month in BS (1-12)
 * @param nepaliDay - Day in BS (1-31)
 * @returns JS Date object
 */
export function nepaliToGregorian(
  nepaliYear: number,
  nepaliMonth: number,
  nepaliDay: number
): Date {
  const baseGregorian = new Date(1945, 0, 1);
  const baseNepali = { year: 2001, month: 10, day: 16 };

  let totalDays = 0;

  // Calculate days from base Nepali date
  for (let year = baseNepali.year; year < nepaliYear; year++) {
    const yearData = NEPALI_CALENDAR_DATA.find((data) => data[0] === year);
    if (yearData) {
      for (let i = 1; i <= 12; i++) {
        totalDays += yearData[i];
      }
    }
  }

  // Add days from months in the target year
  const yearData = NEPALI_CALENDAR_DATA.find((data) => data[0] === nepaliYear);
  if (yearData) {
    for (let month = 1; month < nepaliMonth; month++) {
      totalDays += yearData[month];
    }
  }

  // Add remaining days
  totalDays += nepaliDay - baseNepali.day;

  // Convert back to Gregorian
  const resultDate = new Date(baseGregorian);
  resultDate.setDate(resultDate.getDate() + totalDays);

  return resultDate;
}

/**
 * Format Nepali date to ISO string (YYYY-MM-DD)
 * @param nepaliYear - Year in BS
 * @param nepaliMonth - Month in BS (1-12)
 * @param nepaliDay - Day in BS (1-31)
 * @returns ISO date string
 */
export function nepaliToISOString(
  nepaliYear: number,
  nepaliMonth: number,
  nepaliDay: number
): string {
  const gregorianDate = nepaliToGregorian(nepaliYear, nepaliMonth, nepaliDay);
  return gregorianDate.toISOString().split("T")[0];
}

/**
 * Parse Nepali date string format (YYYY-MM-DD BS)
 * @param nepaliDateString - Date string in format "2081-05-20"
 * @returns Object with year, month, day
 */
export function parseNepaliDateString(
  nepaliDateString: string
): { year: number; month: number; day: number } {
  const parts = nepaliDateString.split("-");
  return {
    year: parseInt(parts[0], 10),
    month: parseInt(parts[1], 10),
    day: parseInt(parts[2], 10),
  };
}

/**
 * Format Nepali date object to string
 * @param nepaliDate - Object with year, month, day
 * @returns String in format "YYYY-MM-DD"
 */
export function formatNepaliDateObject(nepaliDate: {
  year: number;
  month: number;
  day: number;
}): string {
  return `${nepaliDate.year}-${String(nepaliDate.month).padStart(2, "0")}-${String(nepaliDate.day).padStart(2, "0")}`;
}

/**
 * Get array of Nepali months
 */
export function getNepaliMonths(): string[] {
  return NEPALI_MONTHS;
}

/**
 * Get days in a specific Nepali month
 * @param nepaliYear - Year in BS
 * @param nepaliMonth - Month in BS (1-12)
 * @returns Number of days in that month
 */
export function getDaysInNepaliMonth(nepaliYear: number, nepaliMonth: number): number {
  const yearData = NEPALI_CALENDAR_DATA.find((data) => data[0] === nepaliYear);
  if (!yearData) return 0;
  return yearData[nepaliMonth];
}

/**
 * Get total days in a Nepali year
 * @param nepaliYear - Year in BS
 * @returns Total days in that year
 */
export function getDaysInNepaliYear(nepaliYear: number): number {
  const yearData = NEPALI_CALENDAR_DATA.find((data) => data[0] === nepaliYear);
  if (!yearData) return 0;
  return yearData.slice(1).reduce((sum, days) => sum + days, 0);
}
